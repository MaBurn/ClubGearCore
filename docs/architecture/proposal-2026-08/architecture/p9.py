from dio import Page


def page_storage_backends():
    p = Page("9 · Pluggable storage — local or Nextcloud", 1700, 1170)
    p.text(40, 24, 1200, 30, "Local or Nextcloud — one port, two adapters, per-instance choice", 20, "#0077BA", bold=True)
    p.text(40, 54, 1400, 40,
           "The core defines where bytes and appointments are read and written. The Nextcloud implementation is a plugin, "
           "so the »no vendor in core« rule still holds. The administrator picks the adapter.", 12)

    # consumers
    p.band(40, 110, 360, 400, "Core services that need a store")
    fs = p.node(60, 156, 320, 84, "CORE-02  File storage\nowns metadata, policy,\nauthorisation, audit", "core_new", fontsize=11, bold=True)
    cal = p.node(60, 260, 320, 84, "CORE-07  Calendar\nowns events, registrations,\ncapacity, permissions", "core_new", fontsize=11, bold=True)
    p.text(60, 360, 320, 120,
           "Neither service knows what Nextcloud is.\nThey depend only on the two ports on the right.", 11.5)

    # ports
    p.band(440, 110, 420, 400, "Ports — defined in the core / contract")
    fport = p.node(460, 150, 380, 150,
                   "IFileStorageBackend\n\nput(key, stream, ct)\nopen(key) → stream\ndelete(key) · exists(key)\nhealth() · capabilities()\n\nthe key is generated by the core",
                   "contract", fontsize=11, bold=True)
    cport = p.node(460, 320, 380, 170,
                   "ICalendarStore\n\nreadRange(from, to, syncToken)\nupsert(item, ifMatch) · delete(uid)\nsyncToken() · reportConflicts()\n\ncarries the complete VEVENT:\nfields, attendees, extensions",
                   "contract", fontsize=11, bold=True)

    # adapters
    p.band(900, 110, 380, 400, "Adapters")
    a1 = p.node(920, 150, 340, 66, "Local filesystem backend\nships with the core · default", "core", fontsize=11)
    a2 = p.node(920, 226, 340, 74, "Nextcloud WebDAV backend\nclubgear.plugin.nextcloud", "plugin", fontsize=11)
    a3 = p.node(920, 320, 340, 66, "Local calendar store\nClubGear database · default", "core", fontsize=11)
    a4 = p.node(920, 396, 340, 94, "Nextcloud CalDAV store\nclubgear.plugin.nextcloud\ncredentials, discovery, chunking", "plugin", fontsize=11)

    # external
    ext = p.node(1340, 260, 320, 110, "Your Nextcloud\n\nWebDAV  /ClubGear/storage\nCalDAV  calendar collections\ndedicated service account", "ext", fontsize=11, bold=True)

    E = p.edge
    E(fs, fport); E(cal, cport)
    E(fport, a1); E(fport, a2); E(cport, a3); E(cport, a4)
    E(a2, ext, "", "#5b3d86", dashed=1); E(a4, ext, "", "#5b3d86", dashed=1)

    # what stays local
    p.band(40, 540, 800, 300, "Stays in ClubGear whichever adapter is active")
    left = ["File metadata: id, scope, display name, media type, size, checksum, state",
            "Which backend currently holds each object — so a migration can run online",
            "Every authorisation decision; a Nextcloud share link is never the access path",
            "Audit entries for upload, replacement, deletion and sensitive downloads"]
    right = ["A discardable read cache — no events or registrations table of its own",
             "The member ↔ ATTENDEE link, so a deletion request can be honoured",
             "Audit entries for what was changed through ClubGear",
             "Notification records for invitations and change notices"]
    p.text(60, 578, 380, 20, "Files", 12.5, "#16354f", bold=True)
    for i, l in enumerate(left):
        p.text(60, 602 + i * 42, 380, 40, "· " + l, 11)
    p.text(460, 578, 360, 20, "Calendar  (Nextcloud mode — see page 10)", 12.5, "#16354f", bold=True)
    for i, l in enumerate(right):
        p.text(460, 602 + i * 42, 360, 40, "· " + l, 11)

    # rules
    p.band(880, 540, 780, 300, "Rules that make the choice safe")
    rules = [
        ("No silent fallback", "If the selected backend is unreachable, the operation fails with a clear error.\nClubGear never quietly writes to the other store — same rule as the channels."),
        ("Switching is a verified copy, not a toggle", "Changing the backend starts a resumable job. Source objects are deleted only after\nthe checksum is verified at the destination; both stores stay readable meanwhile."),
        ("Uninstall is guarded", "The Nextcloud plugin cannot be removed while objects or calendars still live there.\nThe host requires a migration back to local first."),
        ("Files and calendar differ deliberately", "Files: metadata stays in ClubGear, only the bytes move. Calendar: the whole entry\nlives in Nextcloud and ClubGear keeps only a cache. That is the explicit instruction."),
        ("Credentials are secrets", "App password encrypted at rest, redacted in UI and logs, never returned by the\nordinary configuration API."),
    ]
    y = 578
    for title, body in rules:
        p.text(900, y, 740, 18, title, 12, "#16354f", bold=True)
        p.text(900, y + 20, 740, 40, body, 10.8)
        y += 52

    p.band(40, 870, 1620, 260, "Why this shape, and what it costs")
    p.text(60, 908, 500, 20, "Why a port rather than »Nextcloud support«", 12.5, "#187344", bold=True)
    p.text(60, 934, 500, 170,
           "Clubmanager wired Nextcloud directly into the calendar and the document features:\n"
           "NextcloudCalendarService is 42 KB, NextcloudDocumentService 26 KB, WebDavService 19 KB,\n"
           "and both config tables store the app password in plain text with a »TODO: encrypt«.\n\n"
           "A port keeps that code in one plugin, keeps the credentials in the plugin's namespaced\n"
           "secret store, and keeps a ClubGear installation without Nextcloud fully functional.", 11)
    p.text(600, 908, 500, 20, "What it costs", 12.5, "#c98a1e", bold=True)
    p.text(600, 934, 500, 170,
           "· CORE-02 grows by roughly S: a backend interface, a backend column on the metadata\n"
           "  row, a migration job and an integrity check.\n"
           "· CORE-07 grows by roughly M–L: the store port, the cache and the optimistic write\n"
           "  path replace both the local event tables and the separate CalDAV connector that the\n"
           "  original backlog listed as CALDAV-01.\n"
           "· The Nextcloud plugin itself is M–L: WebDAV, CalDAV, discovery, chunked upload,\n"
           "  conflict reporting and health checks.", 11)
    p.text(1140, 908, 500, 20, "What it does not change", 12.5, "#0077BA", bold=True)
    p.text(1140, 934, 500, 170,
           "· The sequence. Both ports are designed with CORE-02 and CORE-07; the Nextcloud\n"
           "  adapter can ship later without another core change.\n"
           "· The boundary. No Nextcloud type, config key or path appears in the core.\n"
           "· Plugin storage. A plugin still calls the core file service; it never sees WebDAV.\n"
           "· The default. A fresh installation runs entirely local, with no external dependency.", 11)
    return p
